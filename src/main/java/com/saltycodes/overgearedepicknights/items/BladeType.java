    private final String name;
    private final String displayName;
    private final String suffix;
    private final String part;
    private final String tooltype;
    private final boolean addon;
    private final String resultTemplate;
    private final Set<BladeMaterial> materials;
    private final int castingAmount;
    private final boolean castableType;
    private final String[] knapPattern;
    private final int forgeHammering;
    private final String[] forgePattern;
    private final Map<Character, String> forgeKeys;
    private final String[] assemblyIngredients;
    private final String[] stoneBladePattern;

    BladeType(Spec s) {
        this.name = s.name;
        this.displayName = s.displayName;
        this.suffix = s.suffix;
        this.part = s.part;
        this.tooltype = s.tooltype != null ? s.tooltype : s.name;
        this.addon = s.addon;
        this.resultTemplate = s.resultTemplate != null ? s.resultTemplate
                : (s.addon ? "magistuarmoryaddon" : "magistuarmory") + ":{mat}_" + s.name;
        this.materials = s.materials == null
                ? Collections.unmodifiableSet(EnumSet.allOf(BladeMaterial.class))
                : Collections.unmodifiableSet(EnumSet.copyOf(Arrays.asList(s.materials)));
        this.castingAmount = s.castingAmount;
        this.castableType = s.castableType;
        this.knapPattern = s.knapPattern;
        this.forgeHammering = s.forgeHammering;
        this.forgePattern = s.forgePattern;
        this.forgeKeys = Collections.unmodifiableMap(s.forgeKeys);
        this.assemblyIngredients = s.assemblyIngredients;
        this.stoneBladePattern = s.stoneBladePattern;
        if (forgePattern == null) throw new IllegalStateException(name + ": forge pattern missing");
        for (String row : forgePattern) {
            for (char c : row.toCharArray()) {
                if (c != ' ' && !forgeKeys.containsKey(c)) {
                    throw new IllegalStateException(name + ": no key for '" + c + "'");
                }
            }
        }
    }

