    /** Registry-name stem, e.g. {@code shortsword}; also the default tool type and blueprint id. */
    public String getName() { return name; }
    /** English name of the weapon, e.g. {@code Short Sword}. */
    public String getDisplayName() { return displayName; }
    /** Item-id suffix, {@code _blade} unless overridden. */
    public String getSuffix() { return suffix; }
    /** English name of the forged part, e.g. {@code Blade} or {@code Head}. */
    public String getPart() { return part; }
    /** Overgeared tool type / blueprint id. */
    public String getTooltype() { return tooltype; }
    public boolean isAddon() { return addon; }
    public Set<BladeMaterial> getMaterials() { return materials; }
    /** Metal units needed for casting (0 = no casting). */
    public int getCastingAmount() { return castingAmount; }
    public boolean hasCasting() { return castingAmount > 0; }
    /** Whether a clay/nether tool cast exists for this tool type (listed in casting_tooltypes). */
    public boolean isCastableType() { return castableType; }
    public String[] getKnapPattern() { return knapPattern; }
    public boolean hasKnapping() { return knapPattern != null; }
    public int getForgeHammering() { return forgeHammering; }
    public String[] getForgePattern() { return forgePattern; }
    /** Forging grid keys, see the class comment for the spec syntax. */
    public Map<Character, String> getForgeKeys() { return forgeKeys; }
    /** Extra shapeless-assembly ingredients, or {@code null} when the assembly is a custom shaped recipe. */
    public String[] getAssemblyIngredients() { return assemblyIngredients; }
    public String[] getStoneBladePattern() { return stoneBladePattern; }
    public boolean hasStoneBlade() { return stoneBladePattern != null; }

    /** Item id path of the blade for a material, e.g. {@code steel_shortsword_blade}. */
    public String itemPath(BladeMaterial mat) { return mat.getName() + "_" + name + suffix; }
    /** Full blade item id. */
    public String itemId(BladeMaterial mat) { return OvergearedEpicKnights.MODID + ":" + itemPath(mat); }
    /** The Epic Knights item the blade assembles into. */
    public String resultId(BladeMaterial mat) { return resultTemplate.replace("{mat}", mat.getName()); }
    /** English item name, e.g. {@code Steel Short Sword Blade}; single-material items omit the material. */
    public String itemName(BladeMaterial mat) {
        String base = displayName + " " + part;
        return materials.size() == 1 ? base : mat.getDisplayName() + " " + base;
    }
    /** The material the blueprint-crafting recipe uses as representative (steel if available). */
    public BladeMaterial canonicalMaterial() {
        BladeMaterial first = null;
        for (BladeMaterial m : materials) {
            if (m == BladeMaterial.STONE) continue;
            if (m == BladeMaterial.STEEL) return m;
            if (first == null) first = m;
        }
        return first != null ? first : BladeMaterial.STEEL;
    }

    // ── Availability (addon entries need Epic Knights: Addon) ─────────────────

    private static Boolean addonLoaded;

    public static boolean isAddonLoaded() {
        if (addonLoaded == null) {
            ModList list = ModList.get();
            addonLoaded = list != null && list.isLoaded(OvergearedEpicKnights.ADDON_MODID);
        }
        return addonLoaded;
    }

    /** True when this entry's items are registered in the current game (base entries always are). */
    public boolean isAvailable() { return !addon || isAddonLoaded(); }

    /** All entries whose items exist in this game. Use instead of {@link #values()} at runtime. */
    public static List<BladeType> active() {
        List<BladeType> out = new ArrayList<>();
        for (BladeType t : values()) if (t.isAvailable()) out.add(t);
        return out;
    }

    /** Entries of one section, regardless of availability (DataGen iterates these). */
    public static List<BladeType> of(boolean addon) {
        List<BladeType> out = new ArrayList<>();
        for (BladeType t : values()) if (t.addon == addon) out.add(t);
        return out;
    }

    // ── Spec builder ─────────────────────────────────────────────────────────

    private static Spec spec(String name, String displayName) { return new Spec(name, displayName); }

    static final class Spec {
        final String name, displayName;
        String suffix = "_blade", part = "Blade", tooltype, resultTemplate;
        boolean addon, castableType;
        BladeMaterial[] materials;
        int castingAmount, forgeHammering;
        String[] knapPattern, forgePattern, stoneBladePattern;
        String[] assemblyIngredients = new String[0];
        final Map<Character, String> forgeKeys = new LinkedHashMap<>();

        Spec(String name, String displayName) { this.name = name; this.displayName = displayName; }

        /** Epic Knights: Addon entry — steel only, result in the addon namespace, data in the addon pack. */
        Spec addon() { addon = true; materials = new BladeMaterial[]{BladeMaterial.STEEL}; return this; }
        Spec suffix(String s) { suffix = s; return this; }
        Spec part(String p) { part = p; return this; }
        Spec tooltype(String t) { tooltype = t; return this; }
        /** Assembly result id; {@code {mat}} is replaced by the material name. */
        Spec result(String template) { resultTemplate = template; return this; }
        Spec materials(BladeMaterial... m) { materials = m; return this; }
        Spec cast(int units) { castingAmount = units; return this; }
        Spec castableType() { castableType = true; return this; }
        Spec knap(String... rows) { knapPattern = rows; return this; }
        Spec forge(int hammering, String... rows) { forgeHammering = hammering; forgePattern = rows; return this; }
        Spec key(char c, String spec) { forgeKeys.put(c, spec); return this; }
        Spec assemble(String... ingredients) { assemblyIngredients = ingredients; return this; }
        Spec customAssembly() { assemblyIngredients = null; return this; }
        Spec stoneBlade(String... rows) { stoneBladePattern = rows; return this; }
    }
